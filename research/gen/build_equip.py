"""Build public/equipment.js from research/equipment_catalogue.json.
AJEquip = {g:[[group, [ids]]], i:{id:[name, aliases, loading, common_in]}, img:[ids with an image in public/img/eq]}"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
c = json.load(open(os.path.join(ROOT, "research", "equipment_catalogue.json")))
imgdir = os.path.join(ROOT, "public", "img", "eq")
have = sorted(f[:-5] for f in os.listdir(imgdir) if f.endswith(".webp")) if os.path.isdir(imgdir) else []
groups = []
for g in c["groups"]:
    ids = [i["id"] for i in c["items"] if i["group"] == g["name"]]
    groups.append([g["name"], ids])
items = {i["id"]: [i["name"], "|".join(i.get("aliases", [])), i.get("loading", ""), i.get("common_in", [])] for i in c["items"]}
out = "/* Generated by research/gen/build_equip.py from research/equipment_catalogue.json. Do not edit by hand. */\n"
out += "window.AJEquip=" + json.dumps({"g": groups, "i": items, "img": have}, separators=(",", ":"), ensure_ascii=False) + ";\n"
open(os.path.join(ROOT, "public", "equipment.js"), "w").write(out)
print(len(items), "items,", len(groups), "groups,", len(have), "images,", len(out), "bytes")
