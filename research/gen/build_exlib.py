"""Build public/exlib.js from research/exercise_library.json (635 exercises).
The app's hand-tuned library (onboard.js, 203 lifts) stays as is; this adds the rest for search, swaps and
"add an exercise", plus other names and coaching cues for every lift. Extra lifts are flagged xl so the plan
generator doesn't pick them automatically (only the hand-tuned ones are ranked for plans)."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ex = json.load(open(os.path.join(ROOT, "research", "exercise_library.json")))
cat = {i["id"]: i for i in json.load(open(os.path.join(ROOT, "research", "equipment_catalogue.json")))["items"]}
FIX = {"plates":"bb", "iso_chestpress":"isochestpress", "iso_inclinepress":"isoincpress", "iso_widechest":"isochestpress",
       "iso_benchpress":"isochestpress", "vest":"weightvest", "iso_frontpd":"latpdplate", "sealbench":"sealrow", "iso_row":"rowm",
       "iso_dyrow":"dyrow", "iso_shoulderpress":"isoshoulderpress", "vikingpress":"vikingm", "ohtriextm":"triextm",
       "leversquat":"supersquat", "sissybench":"sissy", "gripper":"grippers", "hurdles":"agility"}
BB = {"bb","ez","trapbar","ssb","swissbar","cambered","axle","fixedbb","landmine","bumpers","earthquake","tricepbar"}
DB = {"db","kb","adjdb","adjkb","heavydb","clubs","mace","circusdb"}
def eqcat(q):
    if any(x in BB for x in q): return "bb"
    if any(x in DB for x in q): return "db"
    if any(x.startswith("cable") or x in ("functional","latpd","latrow","seatedcablerow","diypulley","jungle") for x in q): return "cable"
    if any(cat.get(x, {}).get("loading") in ("selectorised","plate-loaded") or x == "smith" for x in q): return "machine"
    if not q or all(cat.get(x, {}).get("loading") == "bodyweight" for x in q): return "bw"
    return "other"
out, bad = {}, set()
for e in ex:
    q = [FIX.get(x, x) for x in e["equipment"]]
    bad |= {x for x in q if x not in cat}
    lo, hi = e["reps"]
    out[e["key"]] = {"n": e["name"], "p": e["pattern"], "mu": e["muscles"], "q": q, "c": e["compound"], "len": e["stretch"],
                     "lo": lo, "hi": hi, "rest": e["rest_s"], "eq": eqcat(q), "cues": e["cues"], "al": e["aliases"],
                     "vars": e["variations"], **({"uni": True} if e["unilateral"] else {}), **({"unit": e["unit"]} if e.get("unit") else {})}
s = "/* Generated by research/gen/build_exlib.py from research/exercise_library.json. Do not edit by hand. */\nwindow.AJExLib=" + json.dumps(out, separators=(",", ":"), ensure_ascii=False) + ";\n"
open(os.path.join(ROOT, "public", "exlib.js"), "w").write(s)
print(len(out), "exercises,", len(s), "bytes; unknown equipment:", sorted(bad))
