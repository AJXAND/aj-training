"""Build public/sportelite.js from research/sport_elite/<id>.json, and add new sports to public/sportprofiles.js.
AJSportElite = {<id>: {variants, sessions, conditioning, tests, week, primer, taper, rules, sources}}
Exercise keys not in the app library are dropped (and reported); a slot with no valid key left is dropped."""
import json, os, glob, re
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SE = os.path.join(ROOT, "research", "sport_elite")
KEYS = {l.split("\t")[0] for l in open(os.path.join(ROOT, "research", "gen", "exkeys.tsv")).read().splitlines()[1:]}
PREHAB = set("nordic copenhagen shoulderER neck ankle landing calf wrist fingers lowback hipAbd patellar elbow trunkLat hipFlex tspine scap hipRot shin".split())
GROUP = {"Team": "Team field", "Water": "Snow & water", "Snow": "Snow & water", "Wheels": "Endurance", "Track and field": "Athletics",
         "Precision": "Other", "Artistic": "Other"}
COURT = {"basketball", "netball", "volleyball", "handball", "korfball", "icehockey", "waterpolo"}
PROFILE_F = ["q", "prehab", "season", "avoidBefore", "energy", "summary", "evidence", "confidence"]
ELITE_F = ["variants", "sessions", "conditioning", "tests", "week", "primer", "taper", "rules", "sources"]

def clean(o):
    if isinstance(o, str): return re.sub(r"\s*—\s*", ", ", o).replace("–", "-") if "—" in o else o
    if isinstance(o, list): return [clean(x) for x in o]
    if isinstance(o, dict): return {k: clean(v) for k, v in o.items()}
    return o

P = os.path.join(ROOT, "public", "sportprofiles.js")
src = open(P).read()
head, body = src[:src.index("window.AJSportProfiles")], src[src.index("=") + 1:].rstrip().rstrip(";")
prof = json.loads(body)
byid = {s["id"]: s for s in prof["sports"]}
elite, dropped, added, missing = {}, [], [], []
for f in sorted(glob.glob(os.path.join(SE, "*.json"))):
    d = clean(json.load(open(f)))
    sid = d["id"]
    for ph, ss in (d.get("sessions") or {}).items():
        for s in ss:
            keep = []
            for sl in s.get("slots", []):
                ok = [k for k in sl.get("ex", []) if k in KEYS]
                dropped += [f"{sid}:{k}" for k in sl.get("ex", []) if k not in KEYS]
                if ok: sl["ex"] = ok; keep.append(sl)
            s["slots"] = keep
    for v in d.get("variants") or []:
        v["prehab"] = [k for k in v.get("prehab", []) if k in PREHAB]
        for x in v.get("add", []): x["ex"] = [k for k in x.get("ex", []) if k in KEYS]
        v["add"] = [x for x in v.get("add", []) if x["ex"]]
    missing += [f"{sid}: {m.get('name')}" for m in d.get("missing_ex") or []]
    elite[sid] = {k: d[k] for k in ELITE_F if d.get(k) not in (None, [], {})}
    p = byid.get(sid)
    if not p:
        g = d.get("group", "Other")
        p = {"id": sid, "name": d["name"], "aliases": d.get("aliases", []), "group": "Team court" if sid in COURT else GROUP.get(g, g)}
        prof["sports"].append(p); byid[sid] = p; added.append(sid)
    else:
        p["aliases"] = sorted(set(p.get("aliases", [])) | set(d.get("aliases", [])), key=str.lower)
    for k in PROFILE_F:
        if d.get(k) not in (None, [], {}): p[k] = d[k]
    if "prehab" in p: p["prehab"] = [k for k in p["prehab"] if k in PREHAB]
    if not p.get("q"): print("WARNING no q for", sid)
open(P, "w").write(head + "window.AJSportProfiles = " + json.dumps(prof, ensure_ascii=False, separators=(",", ":")) + ";\n")
out = "/* Generated by research/gen/build_sport_elite.py from research/sport_elite/*.json. Do not edit by hand. */\nwindow.AJSportElite=" + json.dumps(elite, ensure_ascii=False, separators=(",", ":")) + ";\n"
open(os.path.join(ROOT, "public", "sportelite.js"), "w").write(out)
print(len(elite), "sports with coaching data,", len(out), "bytes; new sports:", added)
print("dropped exercise keys:", dropped)
print("exercises the research wanted that the library lacks:", missing)
